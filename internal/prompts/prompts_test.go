// argvLimit is Linux's MAX_ARG_STRLEN. Copilot receives its prompt as one argv
// entry, so a prompt near this size fails to start, and the task context added
// at dispatch needs room on top.
const argvLimit = 128 * 1024

func TestGetReturnsSelfContainedText(t *testing.T) {
	t.Parallel()

	invocation := regexp.MustCompile("(?m)(^|[\\s`\"])[/$](adversarial-review|adversarial-test|staff-code-review|plan-critic|sybra-[a-z-]+)\\b")
	for name := range sections {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			text, err := Get(name)
			if err != nil {
				t.Fatal(err)
			}
			if len(text) > argvLimit/2 {
				t.Errorf("prompt is %d bytes, too close to the %d argv limit", len(text), argvLimit)
			}
			if m := invocation.FindString(text); m != "" {
				t.Errorf("prompt invokes a skill: %q", m)
			}
			for _, banned := range []string{"$ARGUMENTS", "SKILL.md", "references/", "subagent_type: \"adversarial", "staff-code-review"} {
				if strings.Contains(text, banned) {
					t.Errorf("prompt still contains %q", banned)
				}
			}
		})
	}
}

func TestGetRejectsUnknownName(t *testing.T) {
	t.Parallel()
	if _, err := Get("no-such-prompt"); err == nil {
		t.Fatal("Get should reject an unknown name")
	}
}

func TestAdversarialPromptsCarryVendoredMandates(t *testing.T) {
	t.Parallel()

	cases := map[string][]string{
		AdversarialReview: {"You are the **Code Adversary**", "You are the **Findings Adversary**", "Review Verdict: FAILED"},
		AdversarialTest:   {"You are the **Test Adversary**", "`PASS (partial)` | `PASS` | `pass`", "`unable_to_run_reason`"},
	}
	for name, wants := range cases {
		text := MustGet(name)
		for _, want := range wants {
			if !strings.Contains(text, want) {
				t.Errorf("%s missing %q", name, want)
			}
		}
	}
}

func TestPRReviewNamesTheTargetAndNeverApproves(t *testing.T) {
	t.Parallel()

	text := PRReview("Automaat/example", 123)
	for _, want := range []string{
		"Review https://github.com/Automaat/example/pull/123",
		"repos/Automaat/example/pulls/123/reviews",
		"NEVER submit an APPROVE review event",
		"`Review Verdict: FAILED`: post nothing",
		"Add every surviving finding",
		"_Generated by Sybra harness_",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("prompt missing %q", want)
		}
	}
	if strings.Contains(text, "%!") {
		t.Error("prompt has a format verb error")
	}
}
