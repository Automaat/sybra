// Package prompts holds the agent instructions Sybra delivers inline in a
// dispatch prompt, so every provider receives the same text and nothing has to
// be installed on the host.
package prompts

import (
	"embed"
	"fmt"
	"strings"
)

// Prompt names accepted by Get.
const (
	AdversarialReview = "adversarial-review"
	AdversarialTest   = "adversarial-test"
	PlanCritic        = "plan-critic"
	SelfMonitor       = "self-monitor"
)

//go:embed data/*.md data/sai/*.md
var files embed.FS

// sections lists the files a prompt is assembled from, in order. A title is
// the heading a mandate gets, so a procedure can refer to it by name.
var sections = map[string][]section{
	AdversarialReview: {
		{file: "data/adversarial-review.md"},
		{title: "Code Adversary mandate", file: "data/sai/code-adversary.md"},
		{title: "Findings Adversary mandate", file: "data/sai/findings-adversary.md"},
	},
	AdversarialTest: {
		{file: "data/adversarial-test.md"},
		{title: "Test Adversary mandate", file: "data/sai/test-adversary.md"},
	},
	PlanCritic:  {{file: "data/plan-critic.md"}},
	SelfMonitor: {{file: "data/self-monitor.md"}},
}

type section struct {
	title string
	file  string
}

// Get returns the named prompt's full text.
func Get(name string) (string, error) {
	parts, ok := sections[name]
	if !ok {
		return "", fmt.Errorf("unknown prompt %q", name)
	}
	var b strings.Builder
	for i, part := range parts {
		data, err := files.ReadFile(part.file)
		if err != nil {
			return "", fmt.Errorf("read prompt %q: %w", name, err)
		}
		if i > 0 {
			b.WriteString("\n\n")
		}
		if part.title != "" {
			fmt.Fprintf(&b, "---\n\n# %s\n\n", part.title)
		}
		b.WriteString(strings.TrimSpace(string(data)))
	}
	return b.String(), nil
}

// MustGet returns the named prompt's full text and panics on an unknown name,
// which only a programming error can produce: the set is fixed at build time.
func MustGet(name string) string {
	text, err := Get(name)
	if err != nil {
		panic(err)
	}
	return text
}

// PRReview returns the instructions for reviewing a pull request and posting
// the result, shared by the pr-review workflow and inbound review dispatch.
func PRReview(projectID string, prNumber int) string {
	url := fmt.Sprintf("https://github.com/%s/pull/%d", projectID, prNumber)
	return MustGet(AdversarialReview) + fmt.Sprintf(`

---

# Review target

Review %[1]s, using the PR title and body as task context.

This task is an authorized Sybra PR review for the linked project. Do not ask the operator for confirmation before posting your review.

You have no approval authority: NEVER submit an APPROVE review event. Do not run `+"`gh pr review --approve`"+` and do not submit `+"`event=APPROVE`"+` via `+"`gh api`"+`. REQUEST_CHANGES and COMMENT are feedback, not approval authority, so submit those directly instead of leaving them pending.

Before posting, fetch the PR head SHA and existing reviews; if a review for that head already contains the Sybra harness footer, do not create another review.

Use GitHub's review API so findings become inline comments, not one aggregated comment. Add every surviving finding as a `+"`comments`"+` entry on the changed line it applies to. Put only the short verdict and summary in the review body.

Post via `+"`gh api repos/%[2]s/pulls/%[3]d/reviews -X POST ...`"+` with explicit `+"`-f`"+`/`+"`-F`"+` fields such as `+"`comments[][path]`"+`, `+"`comments[][line]`"+`, `+"`comments[][side]=RIGHT`"+`, and `+"`comments[][body]`"+`, then choose the event by verdict:

- `+"`Review Verdict: NEEDS_FIXES`"+`: submit with `+"`-f event=REQUEST_CHANGES`"+`.
- `+"`Review Verdict: CLEAN`"+` with a suggestion or question worth surfacing: submit with `+"`-f event=COMMENT`"+`.
- `+"`Review Verdict: CLEAN`"+` with nothing to say: omit `+"`event`"+` so GitHub leaves the review PENDING for a human to approve.
- `+"`Review Verdict: FAILED`"+`: post nothing. Report the `+"`Gate failure:`"+` line as your final message.

End the review summary and every review comment you post with a blank line then exactly this standalone harness attribution footer:

_Generated by Sybra harness_`, url, projectID, prNumber)
}
