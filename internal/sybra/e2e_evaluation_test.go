const testDirectReviewWorkflowYAML = `id: test-direct-review
name: Test Direct Review
steps:
  - id: review
    name: Review
    type: run_agent
    config:
      role: review
      mode: headless
      provider: codex
      prompt: >-
        Review https://github.com/Automaat/sybra/pull/123 directly.

        End the review summary and every review comment you post with a blank
        line then the harness attribution footer, exactly:
        '_Generated by Sybra harness_'.
    next:
      - goto: set_done
  - id: set_done
    name: Set Done
    type: set_status
    config:
      status: done
    next:
      - goto: ""
`

func TestE2E_EvaluationReportSplitsDirectAndSkillReviewCohorts(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	writeSkillFixture(t, home, ".claude", "staff-code-review")

	env := setupE2EMultiProvider(t, "codex", []string{"success", "success"})
	writeWorkflowFixture(t, env, "test-direct-review", testDirectReviewWorkflowYAML)
	skillWorkflowID := "test-review-skill-staff_code_review"
	writeWorkflowFixture(t, env, skillWorkflowID, fmt.Sprintf(testReviewSkillWorkflowYAML, "staff_code_review", "staff-code-review"))

	statsPath := filepath.Join(env.taskDir, "stats.json")
	statsStore, err := stats.NewStore(statsPath)
	if err != nil {
		t.Fatal(err)
	}
	auditDir := filepath.Join(env.taskDir, "audit")
	auditLogger, err := audit.NewLogger(auditDir)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = auditLogger.Close() })

	wm := worktree.New(worktree.Config{
		WorktreesDir: env.worktreesDir,
		Tasks:        env.tasks,
		Logger:       e2eLogger(),
		AgentChecker: env.agents.HasRunningAgentForTask,
	})
	handler := completion.New(completion.Config{
		Logger:         e2eLogger(),
		Tasks:          env.tasks,
		Worktrees:      wm,
		WorkflowEngine: env.engine,
		Stats:          statsStore,
		Audit:          auditLogger,
	})
	env.onAgentComplete = func(ag *agent.Agent) {
		handler.OnComplete(ag)
	}

	directTask, err := env.tasks.Create("direct review cohort", "", "headless")
	if err != nil {
		t.Fatal(err)
	}
	if err := env.startWorkflow(directTask.ID, "test-direct-review"); err != nil {
		t.Fatal(err)
	}
	waitFor(t, 30*time.Second, "direct review workflow completes", func() bool {
		tk, gErr := env.tasks.Get(directTask.ID)
		return gErr == nil &&
			tk.Workflow != nil &&
			tk.Workflow.State == workflow.ExecCompleted &&
			statsStore.Query().AllTime.TotalRuns == 1
	})

	skillTask, err := env.tasks.Create("skill review cohort", "", "headless")
	if err != nil {
		t.Fatal(err)
	}
	if err := env.startWorkflow(skillTask.ID, skillWorkflowID); err != nil {
		t.Fatal(err)
	}
	waitFor(t, 30*time.Second, "skill review workflow completes", func() bool {
		tk, gErr := env.tasks.Get(skillTask.ID)
		return gErr == nil &&
			tk.Workflow != nil &&
			tk.Workflow.State == workflow.ExecCompleted &&
			statsStore.Query().AllTime.TotalRuns == 2
	})

	now := time.Now().UTC()
	rep, err := evaluation.NewService(evaluation.Deps{
		Cfg:   config.EvaluationConfig{WindowDays: 7},
		Stats: statsStore,
		Audit: evaluation.AuditDirReader(auditDir),
		Now:   func() time.Time { return now },
	}).Scan(context.Background())
	if err != nil {
		t.Fatalf("evaluation scan: %v", err)
	}

	reviewRows := make([]evaluation.ComparisonBreakdown, 0, len(rep.ByAgentModel))
	for _, row := range rep.ByAgentModel {
		if row.Role == "review" {
			reviewRows = append(reviewRows, row)
		}
	}
	if len(reviewRows) != 2 {
		t.Fatalf("review rows = %+v, want 2 (direct + skill)", reviewRows)
	}

	seen := map[string]int{}
	for _, row := range reviewRows {
		seen[row.SkillConformance]++
		if row.SkillParityUnknown {
			t.Fatalf("row = %+v, want comparable review cohort", row)
		}
		if row.SampleStatus != evaluation.SampleStatusLowSample {
			t.Fatalf("row sample status = %q, want %q", row.SampleStatus, evaluation.SampleStatusLowSample)
		}
	}
	if seen[evaluation.SkillCohortDirect] != 1 || seen[evaluation.SkillCohortSkill] != 1 {
		t.Fatalf("review cohort split = %+v, want exactly one direct and one skill row", seen)
	}
}
